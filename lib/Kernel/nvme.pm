=head1 SYNOPSIS

Utils and helpers for NVMe testing.

On the target:

  use Kernel::nvme qw(nvmet_target_create nvmet_target_delete);
  nvmet_target_delete(nqn => $nqn);
  nvmet_target_create(nqn => $nqn, device => '/dev/vdb', addr => '10.0.2.1');

On the initiator:

  use Kernel::nvme qw(nvme_connect nvme_disconnect);
  my $ns = nvme_connect(nqn => $nqn, addr => '10.0.2.1');    # e.g. 'nvme1n1'
  ...
  nvme_disconnect($nqn);

=cut

my $nvmet_cfs = '/sys/kernel/config/nvmet';

=head2 nvme_target_control_script

  my $script = nvme_target_control_script(
      target_host => 'nvme-target-node00',
      target_addr => '192.168.42.10',
      blkdev      => '/dev/nvme0n1',
  );

Build the text of a C<NVME_TARGET_CONTROL>-compatible shell script, for
running blktests' NVMe-over-Fabrics tests against a real, separate
target machine instead of blktests' own same-host loopback setup (see
L<blktests Documentation/running-tests.md|https://github.com/osandov/blktests>
and C<contrib/nvme_target_control.py> in the blktests source for the
upstream reference). Implements the C<setup>, C<cleanup>, and C<config>
subcommands blktests calls (see C<tests/nvme/rc> and C<common/nvme> in
the blktests source for the exact contract). C<add-ports> is accepted
but left as a stub, matching the upstream reference script - it is only
needed by multi-port ANA test cases, not the base NVMe-over-TCP flow.

Unlike the upstream reference script (which drives a remote nvmetcli
REST API service and a static TOML config, since it assumes no other
coordination between initiator and target), this assumes the target and
initiator are two openQA multimachine SUTs already synchronized via
barriers, with direct root SSH access to each other (the same access
multimachine tests like NFS already rely on). C<setup> and C<cleanup>
SSH into C<target_host> as root and create or tear down, respectively:
an nvmet subsystem, a namespace backed by C<blkdev>, a TCP port bound
to C<target_addr>:C<target_port>, and an allowed host entry - directly
against the target's C<nvmet> configfs tree, no nvmetcli or REST API
service required on either side. C<config --show-*> reports back the
arguments given here - no discovery, no state kept beyond one
setup/cleanup cycle per subsystem.

Arguments:
  target_host - Hostname or IP blktests' initiator can SSH into as
                root to configure the real NVMe target. Required.
  blkdev      - Device or file path on the target host to expose as
                the namespace backing store (e.g. '/dev/nvme0n1').
                Required.
  target_addr - IP address blktests should connect to for NVMe/TCP
                traffic (the target's address on the dedicated test
                VLAN). Defaults to target_host - pass this separately
                whenever SSH management access and NVMe/TCP traffic
                use different addresses.
  target_port - TCP port for the target to listen on (addr_trsvcid).
                Default: 4420 (the IANA-assigned NVMe/TCP port).
  subsysnqn   - Subsystem NQN to create. Default: 'blktests-subsystem-1',
                matching blktests' typical default test subsystem.
  hostnqn     - Host NQN to allow. Default: a fixed
                'nqn.2014-08.org.nvmexpress:uuid:blktests-initiator'.
  hostid      - Host ID reported via 'config --show-hostid'. Default:
                a fixed placeholder UUID; only matters if a test cares
                about a stable, real hostid.
  adrfam      - Address family for the port. Default: 'ipv4'.

Returns: the script text. Use C<deploy_nvme_target_control> to write it
onto the initiator SUT and make it executable, or handle that yourself.

=cut

sub nvme_target_control_script {
    my (%args) = @_;
    my $target_host = $args{target_host} // die 'nvme_target_control_script requires target_host';
    my $blkdev = $args{blkdev} // die 'nvme_target_control_script requires blkdev';
    my $target_addr = $args{target_addr} // $target_host;
    my $target_port = $args{target_port} // 4420;
    my $subsysnqn = $args{subsysnqn} // 'blktests-subsystem-1';
    my $hostnqn = $args{hostnqn} // 'nqn.2014-08.org.nvmexpress:uuid:blktests-initiator';
    my $hostid = $args{hostid} // '4d6e6f74-6520-4120-7265-616c20504b';
    my $adrfam = $args{adrfam} // 'ipv4';

    return <<"SCRIPT";
#!/bin/bash
# Generated by Kernel::nvme::nvme_target_control_script - do not edit by hand.
# Implements the blktests NVME_TARGET_CONTROL contract against a real,
# separate NVMe target over SSH (nvmet configfs, no nvmetcli/REST API).
set -eu

TARGET_HOST='$target_host'
TARGET_ADDR='$target_addr'
TARGET_PORT='$target_port'
DEFAULT_SUBSYSNQN='$subsysnqn'
DEFAULT_HOSTNQN='$hostnqn'
DEFAULT_HOSTID='$hostid'
DEFAULT_BLKDEV='$blkdev'
ADRFAM='$adrfam'

ssh_target() {
    ssh -o BatchMode=yes -o StrictHostKeyChecking=no "root\@\${TARGET_HOST}" "\$1"
}

cmd_setup() {
    local subsysnqn="\$DEFAULT_SUBSYSNQN" hostnqn="\$DEFAULT_HOSTNQN"
    while [[ \$# -gt 0 ]]; do
        case \$1 in
            --subsysnqn) subsysnqn="\$2"; shift 2 ;;
            --hostnqn) hostnqn="\$2"; shift 2 ;;
            *) shift ;;
        esac
    done
    ssh_target "set -eu
NVMET_CFS=/sys/kernel/config/nvmet
mkdir -p \\\$NVMET_CFS/subsystems/\${subsysnqn}
echo 0 > \\\$NVMET_CFS/subsystems/\${subsysnqn}/attr_allow_any_host
mkdir \\\$NVMET_CFS/subsystems/\${subsysnqn}/namespaces/1
echo -n '\${DEFAULT_BLKDEV}' > \\\$NVMET_CFS/subsystems/\${subsysnqn}/namespaces/1/device_path
echo 1 > \\\$NVMET_CFS/subsystems/\${subsysnqn}/namespaces/1/enable
PORT=0
while [ -e \\\$NVMET_CFS/ports/\\\$PORT ]; do PORT=\\\$((PORT + 1)); done
mkdir \\\$NVMET_CFS/ports/\\\$PORT
echo tcp > \\\$NVMET_CFS/ports/\\\$PORT/addr_trtype
echo -n '\${TARGET_ADDR}' > \\\$NVMET_CFS/ports/\\\$PORT/addr_traddr
echo '\${ADRFAM}' > \\\$NVMET_CFS/ports/\\\$PORT/addr_adrfam
echo '\${TARGET_PORT}' > \\\$NVMET_CFS/ports/\\\$PORT/addr_trsvcid
ln -s \\\$NVMET_CFS/subsystems/\${subsysnqn} \\\$NVMET_CFS/ports/\\\$PORT/subsystems/\${subsysnqn}
mkdir -p \\\$NVMET_CFS/hosts/\${hostnqn}
ln -sf \\\$NVMET_CFS/hosts/\${hostnqn} \\\$NVMET_CFS/subsystems/\${subsysnqn}/allowed_hosts/\${hostnqn}
echo \\\$PORT > /run/nvmet-port-\${subsysnqn//\\//_}
"
}

cmd_add_ports() {
    echo "'nvme_target_control add-ports' is a stub" >&2
}

cmd_cleanup() {
    local subsysnqn="\$DEFAULT_SUBSYSNQN"
    while [[ \$# -gt 0 ]]; do
        case \$1 in
            --subsysnqn) subsysnqn="\$2"; shift 2 ;;
            *) shift ;;
        esac
    done
    ssh_target "set -eu
NVMET_CFS=/sys/kernel/config/nvmet
PORT=\\\$(cat /run/nvmet-port-\${subsysnqn//\\//_} 2>/dev/null || echo 0)
rm -f \\\$NVMET_CFS/ports/\\\$PORT/subsystems/\${subsysnqn} 2>/dev/null || true
echo 0 > \\\$NVMET_CFS/subsystems/\${subsysnqn}/namespaces/1/enable 2>/dev/null || true
rmdir \\\$NVMET_CFS/subsystems/\${subsysnqn}/namespaces/1 2>/dev/null || true
rm -f \\\$NVMET_CFS/subsystems/\${subsysnqn}/allowed_hosts/* 2>/dev/null || true
rmdir \\\$NVMET_CFS/subsystems/\${subsysnqn} 2>/dev/null || true
rmdir \\\$NVMET_CFS/ports/\\\$PORT 2>/dev/null || true
rm -f /run/nvmet-port-\${subsysnqn//\\//_}
" || true
}

cmd_config() {
    case "\${1:-}" in
        --show-trtype) echo tcp ;;
        --show-blkdev-type) echo device ;;
        --show-hostnqn) echo "\$DEFAULT_HOSTNQN" ;;
        --show-hostid) echo "\$DEFAULT_HOSTID" ;;
        --show-host-traddr) echo "" ;;
        --show-traddr) echo "\$TARGET_ADDR" ;;
        --show-trsvid) echo "\$TARGET_PORT" ;;
        --show-subsysnqn) echo "\$DEFAULT_SUBSYSNQN" ;;
        --show-subsys-uuid) echo "" ;;
        *) echo "Unknown config query: \${1:-}" >&2; exit 1 ;;
    esac
}

case "\${1:-}" in
    setup) shift; cmd_setup "\$\@" ;;
    add-ports) shift; cmd_add_ports "\$\@" ;;
    cleanup) shift; cmd_cleanup "\$\@" ;;
    config) shift; cmd_config "\$\@" ;;
    *) echo "Usage: \$0 {setup|add-ports|cleanup|config} [args...]" >&2; exit 1 ;;
esac
SCRIPT
}

=head2 deploy_nvme_target_control

  my $path = deploy_nvme_target_control('/usr/local/bin/nvme_target_control', target_host => ..., blkdev => ...);

Write the script built by C<nvme_target_control_script> (same
arguments) to C<$path> on the current SUT and make it executable.
Intended to run on the blktests initiator SUT, immediately before
setting C<NVME_TARGET_CONTROL=$path> and running C<./check nvme>.

Returns: C<$path>.

=cut

sub deploy_nvme_target_control {
    my ($path, %args) = @_;
    my $script = nvme_target_control_script(%args);

    assert_script_run("cat > $path <<'NVME_TARGET_CONTROL_EOF'\n${script}NVME_TARGET_CONTROL_EOF");
    assert_script_run("chmod +x $path");
    return $path;
}

=head2 enable_nvmet_module

  enable_nvmet_module();

Loads the C<nvmet> and C<nvmet-tcp> kernel modules on the current SUT,
so its configfs tree at C</sys/kernel/config/nvmet> exists for the
NVME_TARGET_CONTROL script built above to manipulate. Intended to run
on the target SUT itself, before it signals readiness to the initiator.

=cut

sub enable_nvmet_module {
    assert_script_run('modprobe nvmet');
    assert_script_run('modprobe nvmet-tcp');
}

=head2 mount_configfs

  mount_configfs();

Ensures configfs is mounted at C</sys/kernel/config> on the current
SUT, a no-op if it already is. Required for the C<nvmet> tree
C<enable_nvmet_module> loads to actually be reachable.

=cut

sub mount_configfs {
    assert_script_run('mountpoint -q /sys/kernel/config || mount -t configfs none /sys/kernel/config');
}

=head2 nvmet_target_create

  my $subsys = nvmet_target_create(
      nqn    => 'nqn.2026-10.de.openqa:nvmet-tcp',
      device => '/dev/vdb',
      addr   => '10.0.2.1',
  );

Export one block device as namespace 1 of a new NVMe subsystem, configured
through the C<nvmet> configfs on the current SUT. Load the target modules
and mount configfs first. If firewalld is active, open the port in the
runtime configuration. Make sure that the port listens.

Arguments:
  nqn       - Subsystem NQN. Required.
  device    - Block device or file to export as namespace 1. Required.
  addr      - Address the port listens on (addr_traddr). Required.
  port      - TCP port (addr_trsvcid). Default: 4420.
  port_id   - Directory name of the port in the configfs. Default: 1.
  trtype    - Transport type. Default: 'tcp'.
  adrfam    - Address family. Default: 'ipv4'.
  hostnqn   - Host NQN to allow. Default: none, any host can connect.

Returns: the configfs path of the subsystem.

=cut

sub nvmet_target_create {
    my (%args) = @_;
    my $nqn = $args{nqn} // die 'nvmet_target_create requires nqn';
    my $device = $args{device} // die 'nvmet_target_create requires device';
    my $addr = $args{addr} // die 'nvmet_target_create requires addr';
    my $port = $args{port} // 4420;
    my $port_id = $args{port_id} // 1;
    my $trtype = $args{trtype} // 'tcp';
    my $adrfam = $args{adrfam} // 'ipv4';
    my $subsys = "$nvmet_cfs/subsystems/$nqn";
    my $port_dir = "$nvmet_cfs/ports/$port_id";

    assert_script_run('modprobe nvmet');
    assert_script_run("modprobe nvmet-$trtype");
    mount_configfs();

    assert_script_run("mkdir $subsys");
    if (my $hostnqn = $args{hostnqn}) {
        assert_script_run("echo 0 > $subsys/attr_allow_any_host");
        assert_script_run("mkdir -p $nvmet_cfs/hosts/$hostnqn");
        assert_script_run("ln -s $nvmet_cfs/hosts/$hostnqn $subsys/allowed_hosts/$hostnqn");
    } else {
        assert_script_run("echo 1 > $subsys/attr_allow_any_host");
    }
    assert_script_run("mkdir $subsys/namespaces/1");
    assert_script_run("echo -n $device > $subsys/namespaces/1/device_path");
    assert_script_run("echo 1 > $subsys/namespaces/1/enable");

    assert_script_run("mkdir $port_dir");
    assert_script_run("echo $trtype > $port_dir/addr_trtype");
    assert_script_run("echo $adrfam > $port_dir/addr_adrfam");
    assert_script_run("echo $addr > $port_dir/addr_traddr");
    assert_script_run("echo $port > $port_dir/addr_trsvcid");
    assert_script_run("ln -s $subsys $port_dir/subsystems/$nqn");

    if ($trtype eq 'tcp') {
        assert_script_run("firewall-cmd --add-port=$port/tcp") if script_run('systemctl is-active -q firewalld') == 0;
        assert_script_run("ss -Hltn 'sport = :$port' | grep -q .", fail_message => "NVMe/TCP target does not listen on port $port");
    }
    record_info('nvmet', "$nqn\nnamespace 1: $device\n$trtype $addr:$port");
    return $subsys;
}

=head2 nvmet_target_delete

  nvmet_target_delete(nqn => $nqn);

Remove the subsystem C<nqn> and the port C<port_id> (default: 1) that
C<nvmet_target_create> made. Ignore the parts that do not exist, so you can
use it to clean up before C<nvmet_target_create>. The port stays if another
subsystem uses it.

=cut

sub nvmet_target_delete {
    my (%args) = @_;
    my $nqn = $args{nqn} // die 'nvmet_target_delete requires nqn';
    my $port_id = $args{port_id} // 1;
    my $subsys = "$nvmet_cfs/subsystems/$nqn";
    my $port_dir = "$nvmet_cfs/ports/$port_id";

    script_run("if test -d $subsys; then "
          . "rm -f $port_dir/subsystems/$nqn; "
          . "rmdir $port_dir; "
          . "echo 0 > $subsys/namespaces/1/enable; "
          . "rmdir $subsys/namespaces/1; "
          . "rm -f $subsys/allowed_hosts/*; "
          . "rmdir $subsys; fi");
    assert_script_run("! test -d $subsys", fail_message => "Cannot remove nvmet subsystem $nqn");
}

=head2 nvme_discover

  my $log = nvme_discover(addr => '10.0.2.1');

Load the host module of the transport and run C<nvme discover> against a
target. Return the discovery log. Arguments C<addr> (required), C<port>
(default: 4420) and C<trtype> (default: 'tcp').

=cut

sub nvme_discover {
    my (%args) = @_;
    my $addr = $args{addr} // die 'nvme_discover requires addr';
    my $port = $args{port} // 4420;
    my $trtype = $args{trtype} // 'tcp';

    assert_script_run("modprobe nvme-$trtype");
    return script_output("nvme discover -t $trtype -a $addr -s $port");
}

=head2 nvme_connect

  my $ns = nvme_connect(nqn => $nqn, addr => '10.0.2.1');

Load the host module of the transport and connect to the subsystem C<nqn>.
Wait for its namespace, see C<nvme_namespace_by_nqn>.

Arguments:
  nqn       - Subsystem NQN. Required.
  addr      - Target address. Required.
  port      - Target port. Default: 4420.
  trtype    - Transport type. Default: 'tcp'.
  hostnqn   - Host NQN. Default: the one of nvme-cli (/etc/nvme/hostnqn).

Returns: the block device name of the namespace, e.g. C<nvme1n1>.

=cut

sub nvme_connect {
    my (%args) = @_;
    my $nqn = $args{nqn} // die 'nvme_connect requires nqn';
    my $addr = $args{addr} // die 'nvme_connect requires addr';
    my $port = $args{port} // 4420;
    my $trtype = $args{trtype} // 'tcp';
    my $hostnqn = $args{hostnqn} ? " --hostnqn $args{hostnqn}" : '';

    assert_script_run("modprobe nvme-$trtype");
    assert_script_run("nvme connect -t $trtype -a $addr -s $port -n $nqn$hostnqn");
    return nvme_namespace_by_nqn($nqn);
}

=head2 nvme_disconnect

  nvme_disconnect($nqn);
  nvme_disconnect($nqn, may_fail => 1);

Disconnect all controllers of the subsystem C<nqn>. With C<may_fail>, do
not fail if no controller is connected, e.g. to clean up before
C<nvme_connect>.

=cut

sub nvme_disconnect {
    my ($nqn, %args) = @_;
    my $cmd = "nvme disconnect -n $nqn";

    return script_run($cmd) if $args{may_fail};
    assert_script_run($cmd);
}

=head2 nvme_namespace_by_nqn

  my $ns = nvme_namespace_by_nqn($nqn);
  my $ns = nvme_namespace_by_nqn($nqn, timeout => 60);

Find the first namespace block device of the connected subsystem C<nqn>
in C</sys/class/nvme-subsystem>. The kernel scans the namespaces after the
connect, so wait up to C<timeout> seconds (default: 30).

Returns: the block device name, e.g. C<nvme1n1>. Dies if no namespace
shows up in time.

=cut

sub nvme_namespace_by_nqn {
    my ($nqn, %args) = @_;
    my $timeout = $args{timeout} // 30;
    my $cmd = "s=\$(grep -lx '$nqn' /sys/class/nvme-subsystem/*/subsysnqn) && "
      . "ls \$(dirname \$s) | grep -m1 -E '^nvme[0-9]+n[0-9]+\$'";

    for (1 .. $timeout) {
        my $ns = script_output($cmd, proceed_on_failure => 1);
        return $ns if $ns =~ /^nvme\d+n\d+$/;
        sleep 1;
    }
    die "No namespace of NVMe subsystem $nqn after $timeout seconds";
}

